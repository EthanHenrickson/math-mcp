export class HyperbolicTrig {
    static sinh(x: number): number {
        return Math.sinh(x);
    }

    static cosh(x: number): number {
        return Math.cosh(x);
    }

    static tanh(x: number): number {
        return Math.tanh(x);
    }

    static asinh(x: number): number {
        return Math.asinh(x);
    }

    static acosh(x: number): number {
        return Math.acosh(x);
    }

    static atanh(x: number): number {
        return Math.atanh(x);
    }
}
